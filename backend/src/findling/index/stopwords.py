def folded_stopwords_hash(entries: Sequence[str]) -> str:
    """Return the SHA-256 of the supplement, stable across processes and machines.

    Hashing the joined entries rather than the source file is deliberate, for
    the same reason :func:`findling.index.wordlist.wordlist_hash` does it: what
    decides the behaviour is the derived list, not the bytes it came from. A
    tantivy point release that only reorders a Rust literal must not show up as
    a difference, and one accented entry more or less must.
    """
    digest = hashlib.sha256()
    digest.update("\n".join(entries).encode(ENCODING))
    return digest.hexdigest()
