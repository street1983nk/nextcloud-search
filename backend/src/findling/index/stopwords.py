"""The folded stop word supplement of the Snowball chains, and nothing else.

Where it comes from: the Snowball stop word lists of tantivy, tag 0.26.2, file
``src/tokenizer/stop_word_filter/stopwords.rs`` for Dutch, Italian, Portuguese
and Spanish, and the inline Lucene list in ``mod.rs`` for English. What produced
it: ``scripts/dev/stopword_supplement.py``. It is not edited by hand. A hand
edit produces a supplement that no longer belongs to the list it supplements,
and the symptom of that is a stop word sitting in the index as a term.

Why it exists at all. The built in lists compare strings exactly and they carry
real accents. The chain in :mod:`findling.index.analyzer` folds before it
filters, because that is the only fold position measured to keep the accented
and the flat spelling of a word on one term. Once the fold has run, an entry
like the Spanish "esta" with an accent never matches again, and the flat form it
folded into is in no list at all. Measured on 2026-09-23 against tag 0.26.2: 77
Spanish, 10 Italian and 30 Portuguese stop words would leak into the index as
ordinary terms, in both spellings. This module is the 117 entries that close
that hole. Dutch has no accented entry, English has none either, so both are
empty here, and an empty custom stop word filter is measured to be a no-op.

Every entry is ASCII by construction: it is the folded form of an entry of the
built in list. Accents appear nowhere in this file, not even in a literal, which
is why this module needs no accent note of its own; the note that covers the
test data lives in ``backend/tests/test_language_analyzers.py``. Identifiers
stay ASCII as the project rules require.

**The supplement digest is not a version mark, and it may never become one.**
``folded_stopwords_hash`` below describes this list and belongs into a test. It
must not reach ``expected_versions()`` in :mod:`findling.index.open`. There it
would be a sixth mark, and a sixth mark exists on no installation in the field,
and ``Store.version_mismatch`` reads a missing mark as a difference. The result
would be a full reindex on every stock installation, measured at 19 h 20 min,
caused by a constant that changes no tokenisation of any index already written.
The one place this digest is allowed to stand is
``backend/tests/test_language_analyzers.py``, as ``FOLDED_SUPPLEMENT_SHA256``.

Digest of the list below, over the flattened entries in sorted language order:
d056d4597f989c7e03113c529c92cef980254f72c4d4e5deace4588ea033311a
"""

